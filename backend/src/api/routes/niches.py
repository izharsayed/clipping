"""Niche Gaming Studio routes: templates, voice preview, and 9:16 vertical video rendering."""
import logging
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import FileResponse
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from ...auth_headers import resolve_authenticated_user_id
from ...config import get_config
from ...database import get_db
from ...models import GeneratedClip, Task
from ...services.niche.models import (
    NICHE_METADATA,
    NicheRenderRequest,
    NicheRenderResponse,
    NicheVoicePreviewRequest,
)
from ...services.niche.service import NicheStudioService
from ...services.niche.voice import synth_speech, available_voices

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/niches", tags=["niches"])


async def _user_id(request: Request, db: AsyncSession) -> str:
    return await resolve_authenticated_user_id(request, db, get_config())


@router.get("/templates")
async def get_niche_templates():
    """Retrieve templates, metadata, and schemas for all 7 viral gaming niches."""
    from ...services.niche.service import DEFAULT_PLANS
    return {
        "niches": list(NICHE_METADATA.values()),
        "plans": DEFAULT_PLANS,
        "voices": available_voices(),
    }


@router.post("/preview-voice")
async def preview_niche_voice(
    request_data: NicheVoicePreviewRequest,
    request: Request,
    db: AsyncSession = Depends(get_db),
):
    """Generate and return an audio WAV preview of a niche voiceover."""
    await _user_id(request, db)
    from pathlib import Path
    temp_dir = Path(get_config().temp_dir) / "voice_previews"
    temp_dir.mkdir(parents=True, exist_ok=True)
    out_wav = temp_dir / f"preview_{hash(request_data.text) % 1000000}.wav"
    synth_speech(
        text=request_data.text,
        out_path=out_wav,
        voice=request_data.voice,
        speed=request_data.speed,
    )
    if not out_wav.exists():
        raise HTTPException(status_code=500, detail="Voice synthesis failed")
    return FileResponse(str(out_wav), media_type="audio/wav", filename="preview.wav")


@router.post("/render", response_model=NicheRenderResponse)
async def render_niche_project(
    request_data: NicheRenderRequest,
    request: Request,
    db: AsyncSession = Depends(get_db),
):
    """Render a finished 9:16 vertical video Short in any of the 7 gaming niches."""
    user_id = await _user_id(request, db)
    service = NicheStudioService(db)
    try:
        result = await service.render_niche_short(
            user_id=user_id,
            niche=request_data.niche,
            name=request_data.name,
            plan=request_data.plan,
            output_filename=request_data.output_name,
            video_url=request_data.video_url,
        )
        return NicheRenderResponse(
            success=True,
            task_id=result["task_id"],
            clip_id=result["clip_id"],
            filename=result["filename"],
            duration=result["duration"],
            video_url=result["video_url"],
            cover_url=result.get("cover_url"),
            post_text=result["post_text"],
            qc=result["qc"],
            message=result["message"],
        )
    except Exception as exc:
        logger.exception("Failed to render niche project: %s", exc)
        raise HTTPException(status_code=500, detail=str(exc))


@router.get("/recent")
async def list_recent_niche_clips(
    request: Request,
    db: AsyncSession = Depends(get_db),
):
    """List recent niche short clips generated by the user."""
    user_id = await _user_id(request, db)
    stmt = (
        select(GeneratedClip, Task)
        .join(Task, GeneratedClip.task_id == Task.id)
        .where(Task.user_id == user_id, GeneratedClip.workflow_role == "niche_short")
        .order_by(GeneratedClip.created_at.desc())
        .limit(20)
    )
    rows = (await db.execute(stmt)).all()
    out = []
    for clip, task in rows:
        out.append({
            "task_id": task.id,
            "clip_id": clip.id,
            "filename": clip.filename,
            "duration": clip.duration,
            "created_at": clip.created_at.isoformat() if clip.created_at else None,
            "video_url": f"/api/tasks/{task.id}/clips/{clip.id}/file",
            "niche": clip.workflow_meta.get("niche"),
            "post_text": clip.workflow_meta.get("post_text"),
            "loudness_lufs": clip.workflow_meta.get("loudness_lufs"),
        })
    return out
